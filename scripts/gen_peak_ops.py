"""Generate bench/peak_ops.c: throughput of the NEON ops used by the fp32
SiLU on the Cortex-A72 (16 independent instructions per loop iteration,
registers only).

usage: python -I scripts/gen_peak_ops.py     (from the repository root)
"""
OUT = "bench/peak_ops.c"
OPS = {
    "fmla.4s": "fmla v{d}.4s, v1.4s, v2.4s",
    "fmul.4s": "fmul v{d}.4s, v1.4s, v2.4s",
    "fadd.4s": "fadd v{d}.4s, v1.4s, v2.4s",
    "fmin.4s": "fmin v{d}.4s, v1.4s, v2.4s",
    "frecpe.4s": "frecpe v{d}.4s, v1.4s",
    "frecps.4s": "frecps v{d}.4s, v1.4s, v2.4s",
    "shl.4s": "shl v{d}.4s, v1.4s, #23",
    "add.4s": "add v{d}.4s, v1.4s, v2.4s",
    "sub.4s": "sub v{d}.4s, v1.4s, v2.4s",
    "frintn.4s": "frintn v{d}.4s, v1.4s",
    "fcvtzs.4s": "fcvtzs v{d}.4s, v1.4s",
    "scvtf.4s": "scvtf v{d}.4s, v1.4s",
    "fmla.2s": "fmla v{d}.2s, v1.2s, v2.2s",
    "frecpe.2s": "frecpe v{d}.2s, v1.2s",
    "shl.2s": "shl v{d}.2s, v1.2s, #23",
    "fdiv.4s": "fdiv v{d}.4s, v1.4s, v2.4s",
    "tbl.16b": "tbl v{d}.16b, {{v4.16b, v5.16b, v6.16b, v7.16b}}, v1.16b",
    "mul.4s": "mul v{d}.4s, v1.4s, v2.4s",
    "fcvtl": "fcvtl v{d}.4s, v1.4h",
    "ushr.4s": "ushr v{d}.4s, v1.4s, #9",
    "bsl.16b": "bsl v{d}.16b, v1.16b, v2.16b",
    "and.16b": "and v{d}.16b, v1.16b, v2.16b",
}
NOW_S = ("static double now_s(void) { struct timespec t; "
         "clock_gettime(CLOCK_MONOTONIC, &t); "
         "return t.tv_sec + t.tv_nsec * 1e-9; }")
SETUP = ('  __asm__ volatile("movi v1.4s, #0x3f\\n movi v2.4s, #0x3f\\n '
         "movi v4.16b, #1\\n movi v5.16b, #1\\n movi v6.16b, #1\\n "
         'movi v7.16b, #1\\n" ::: "v1", "v2", "v4", "v5", "v6", "v7");')
PRINTF = ('printf("%-11s %.2f/cycle at 1.5 GHz (%.2f G/s)\\n", "{nm}", '
          "16.0 * n / t / 1.5e9, 16.0 * n / t * 1e-9);")


def run_function(a, i, ins):
    """run_<i>(n): the timed loop of one instruction over v16-v31."""
    a(f"static double run_{i}(long n) {{")
    a(SETUP)
    a("  double t = now_s();")
    a('  __asm__ volatile("1:\\n"')
    for d in range(16, 32):
        a(f'      "{ins.format(d=d)}\\n"')
    clob = ", ".join(f'"v{v}"' for v in range(16, 32))
    a('      "subs %[n], %[n], #1\\n b.ne 1b\\n" : [n] "+r"(n) : : ' + clob
      + ', "cc");')
    a("  return now_s() - t;")
    a("}")


def main():
    lines = ["// generated by scripts/gen_peak_ops.py - do not edit",
             "#include <stdio.h>\n#include <time.h>", NOW_S]
    a = lines.append
    for i, ins in enumerate(OPS.values()):
        run_function(a, i, ins)
    a("int main(void) {\n  long n = 5000000;")
    for i, nm in enumerate(OPS):
        a(f"  {{ double t = run_{i}(n); " + PRINTF.format(nm=nm) + " }")
    a("  return 0;\n}")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
