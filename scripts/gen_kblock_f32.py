"""Generate src/gemm_f32_kblock.h: the fp32 GEMM K loop (8 rows x 8 channels)
as one inline-asm block (plain ARMv8-A NEON: FMLA .4s by element, no fp16
arithmetic, no dotprod; the Cortex-A72 path).

usage: python -I scripts/gen_kblock_f32.py [out.h]   (default: the src/ file)

KB8X8F(A, LDA, W, N4, NSEG, SKIP, A0..A15[, PFD]):
  A      row 0 of the tile (rows r = 0..7 at A + r * LDA bytes; all 8 rows
         must be readable, rows beyond M are computed and dropped by the
         caller), LDA row stride in bytes,
  W      weight panel [K][8] fp32 (advanced; a pointer lvalue),
  N4     k steps of 4 per segment, NSEG segments, SKIP bytes added to every
         row pointer between segments (= segment stride - (N4 + 1) * 16, see
         below),
  A0..A15 float32x4_t lvalues: the accumulators, zeroed here (row r: A{2r}
         ch 0-3, A{2r+1} ch 4-7); they stay in NEON registers for the
         caller's fused epilogue (a store / reload round trip costs ~600
         cycles per tile on the A72). gcc's 30-operand limit (an in/out
         operand counts twice) is why the row pointers are derived here.
Fixed registers: A rows v0-v7 (4 consecutive k each), weights v8-v11 (two k
steps, double-buffered), x9-x16 scratch.
Software pipelining: inside a 4-k iteration the weights of step l+1 are
loaded before the FMLAs of step l, and each A row is reloaded right after its
last use (step 3). The final iteration of a segment therefore reads 16 bytes
past each A row (buffers carry >= 64 bytes of slack) and 32 bytes past the
panel segment (rewound before the next segment). The _PF variant PRFMs the
weight stream PFD bytes ahead (register offset, tuned at run time).
"""
import sys

DEFAULT_OUT = "src/gemm_f32_kblock.h"
ACCS = ", ".join(f"A{i}" for i in range(16))
# row pointers: operand a, then x9..x15
ROWS = ["%[a]"] + [f"x{9+r}" for r in range(7)]


def macro_head(a, pf):
    """The comment and the #define line of one variant."""
    nm = "KB8X8F_PF" if pf else "KB8X8F"
    prefetch = "; prefetches the weight stream PFD bytes ahead" if pf else ""
    a("/* 8 rows x 8 channels fp32 over NSEG segments of N4 steps of 4 k; "
      f"accumulators zeroed here, left in registers{prefetch} */")
    pfd = ", PFD" if pf else ""
    a(f"#define {nm}(A, LDA, W, N4, NSEG, SKIP, {ACCS}{pfd}) \\")
    a("  __asm__ volatile( \\")


def prologue(a):
    """Row pointers from A and LDA, zeroed accumulators, the segment loop."""
    for r in range(1, 8):
        prev = ROWS[r - 1]
        a(f'      "add x{8+r}, {prev}, %[lda]\\n" \\')
    for i in range(16):
        a(f'      "movi %[a{i}].16b, #0\\n" \\')
    a('      "mov x17, %[nseg]\\n" \\')
    a('      "2:\\n" \\')
    a('      "mov x16, %[n4]\\n" \\')
    for r in range(8):
        a(f'      "ldr q{r}, [{ROWS[r]}], #16\\n" \\')
    a('      "ldp q8, q9, [%[w]], #32\\n" \\')
    a('      "1:\\n" \\')


def k_loop(a, pf):
    """The 4-k iteration: weights of the next step, 64 FMLAs, row reloads."""
    for k in range(4):
        cur = 8 if k % 2 == 0 else 10
        nxt = 10 if k % 2 == 0 else 8
        a(f'      "ldp q{nxt}, q{nxt+1}, [%[w]], #32\\n" \\')
        if pf and k == 0:
            a('      "prfm pldl1keep, [%[w], %[pfd]]\\n" \\')
        for r in range(8):
            a(f'      "fmla %[a{2*r}].4s, v{cur}.4s, v{r}.s[{k}]\\n" \\')
            a(f'      "fmla %[a{2*r+1}].4s, v{cur+1}.4s, v{r}.s[{k}]\\n" \\')
            if k == 3:
                a(f'      "ldr q{r}, [{ROWS[r]}], #16\\n" \\')
    a('      "subs x16, x16, #1\\n" \\')
    a('      "b.ne 1b\\n" \\')


def epilogue(a, pf):
    """Panel rewind, the segment skip, the operand lists and clobbers."""
    a('      "sub %[w], %[w], #32\\n" \\')
    for r in range(8):
        a(f'      "add {ROWS[r]}, {ROWS[r]}, %[skip]\\n" \\')
    a('      "subs x17, x17, #1\\n" \\')
    a('      "b.ne 2b\\n" \\')
    a('      : [a] "+r"(A), [w] "+r"(W), \\')
    a("        " + ", ".join(f'[a{i}] "=w"(A{i})' for i in range(16)) + " \\")
    pfd = ', [pfd] "r"((long)(PFD))' if pf else ""
    a('      : [lda] "r"((long)(LDA)), [n4] "r"((long)(N4)), '
      '[nseg] "r"((long)(NSEG)), [skip] "r"((long)(SKIP))' + pfd + " \\")
    clob = (", ".join(f'"v{i}"' for i in range(12)) + ", "
            + ", ".join(f'"x{i}"' for i in range(9, 18)))
    a(f'      : {clob}, "cc", "memory")')


def main():
    lines = ["// generated by scripts/gen_kblock_f32.py - do not edit",
             "#ifndef GEMM_F32_KBLOCK_H", "#define GEMM_F32_KBLOCK_H"]
    for pf in (0, 1):
        macro_head(lines.append, pf)
        prologue(lines.append)
        k_loop(lines.append, pf)
        epilogue(lines.append, pf)
    lines.append("#endif")
    out = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_OUT
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
