"""Generate src/gemm_f16_kblock.h: the fp16 GEMM K-block loop (8 rows x 16
channels) as one inline-asm block with fixed registers (gcc turns by-element
FMLA intrinsics into DUP + FMLA and spills).
Accumulators v16-v31 (row r: v(16+2r) ch 0-7, v(17+2r) ch 8-15), A rows
v0-v7, weights v8-v11 (double-buffered). The accumulators are loaded from /
stored to an fp16 [8][16] buffer around the loop.

usage: python -I scripts/gen_kblock.py     (from the repository root)
"""
OUT = "src/gemm_f16_kblock.h"
PARAMS = ("(const f16 *p0, const f16 *p1, const f16 *p2, const f16 *p3,",
          "    const f16 *p4, const f16 *p5, const f16 *p6, const f16 *p7, "
          "const f16 *w, long n8, f16 *cb) {")
OPERANDS = ('      : [p0] "+r"(p0), [p1] "+r"(p1), [p2] "+r"(p2), '
            '[p3] "+r"(p3), [p4] "+r"(p4), [p5] "+r"(p5), [p6] "+r"(p6),',
            '        [p7] "+r"(p7), [w] "+r"(w), [n] "+r"(n8)',
            '      : [cb] "r"(cb)')


def clobbers(regs):
    """The clobber list of the NEON registers v<i>."""
    return ", ".join(f'"v{i}"' for i in regs)


def acc_comment(zero):
    """How the accumulators start."""
    if zero:
        return "accumulators start at 0"
    return "accumulators loaded from cb"


def head(a, nm, comment):
    """The comment, the function head and the asm opening."""
    a(f"/* {comment} */")
    a(f"static inline __attribute__((always_inline)) void {nm}{PARAMS[0]}")
    a(PARAMS[1])
    a("  __asm__ volatile(")


def tail(a, clob):
    """The operand lists, the clobbers and the closing brace."""
    for line in OPERANDS:
        a(line)
    a(f'      : {clob}, "cc", "memory");')
    a("}")


def loads_8(a):
    """The eight A row loads (one q register per row)."""
    for r in range(8):
        a(f'      "ldr q{r}, [%[p{r}]], #16\\n"')


def loop_end(a):
    """The loop counter and the back branch."""
    a('      "subs %[n], %[n], #1\\n"')
    a('      "b.ne 1b\\n"')


def kblock_8x16(a, zero):
    """kblock[0]_8x16: 8 rows x 16 channels, weights double-buffered in
    q8-q11, accumulators v16-v31."""
    nm = "kblock0_8x16" if zero else "kblock_8x16"
    head(a, nm, f"{acc_comment(zero)}; result stored to cb")
    for r in range(8):
        if zero:
            a(f'      "movi v{16+2*r}.16b, #0\\n"')
            a(f'      "movi v{17+2*r}.16b, #0\\n"')
        else:
            a(f'      "ldp q{16+2*r}, q{17+2*r}, [%[cb], #{32*r}]\\n"')
    # software-pipelined: A rows and the first weight pair are loaded before
    # the loop; inside, the weights of step L+1 are loaded before the FMLAs
    # of step L, and each A row of the next 8-k step is reloaded right after
    # its last use (step 7). The final iteration therefore reads 32 bytes
    # past the weight panel and 16 bytes past each A row (buffers carry
    # >= 64 bytes of slack).
    loads_8(a)
    a('      "ldp q8, q9, [%[w]], #32\\n"')
    a('      "1:\\n"')
    for k in range(8):
        cur = 8 if k % 2 == 0 else 10
        nxt = 10 if k % 2 == 0 else 8
        a(f'      "ldp q{nxt}, q{nxt+1}, [%[w]], #32\\n"')
        for r in range(8):
            a(f'      "fmla v{16+2*r}.8h, v{cur}.8h, v{r}.h[{k}]\\n"')
            a(f'      "fmla v{17+2*r}.8h, v{cur+1}.8h, v{r}.h[{k}]\\n"')
            if k == 7:
                a(f'      "ldr q{r}, [%[p{r}]], #16\\n"')
    loop_end(a)
    for r in range(8):
        a(f'      "stp q{16+2*r}, q{17+2*r}, [%[cb], #{32*r}]\\n"')
    tail(a, clobbers(list(range(12)) + list(range(16, 32))))


def kblock_8x8(a, zero):
    """kblock[0]_8x8 (the N tail): 8 rows x 8 channels, weights in q8-q9,
    accumulators v16-v23."""
    nm = "kblock0_8x8" if zero else "kblock_8x8"
    head(a, nm, f"8 rows x 8 channels (N tail); {acc_comment(zero)}; "
         "stored to cb [8][8]")
    for r in range(8):
        if zero:
            a(f'      "movi v{16+r}.16b, #0\\n"')
        elif r % 2 == 0:
            a(f'      "ldp q{16+r}, q{17+r}, [%[cb], #{16*r}]\\n"')
    loads_8(a)
    a('      "ldr q8, [%[w]], #16\\n"')
    a('      "1:\\n"')
    for k in range(8):
        cur = 8 if k % 2 == 0 else 9
        nxt = 9 if k % 2 == 0 else 8
        a(f'      "ldr q{nxt}, [%[w]], #16\\n"')
        for r in range(8):
            a(f'      "fmla v{16+r}.8h, v{cur}.8h, v{r}.h[{k}]\\n"')
            if k == 7:
                a(f'      "ldr q{r}, [%[p{r}]], #16\\n"')
    loop_end(a)
    for r in range(0, 8, 2):
        a(f'      "stp q{16+r}, q{17+r}, [%[cb], #{16*r}]\\n"')
    tail(a, clobbers(list(range(10)) + list(range(16, 24))))


def main():
    lines = ["// generated by scripts/gen_kblock.py - do not edit",
             "#ifndef GEMM_F16_KBLOCK_H", "#define GEMM_F16_KBLOCK_H"]
    for zero in (0, 1):
        kblock_8x16(lines.append, zero)
    for zero in (0, 1):
        kblock_8x8(lines.append, zero)
    lines.append("#endif")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
