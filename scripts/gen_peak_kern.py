"""Generate bench/peak_kern.c: variants of the 8x8 fp32 GEMM K loop (64 FMLA
.4s per 4-k iteration) to measure what limits it on the Cortex-A72: no loads
/ weight LDPs only / A LDRs only / both (the real kernel) / LDR pairs instead
of LDP. All data L1-resident (pointers rewound every 256 iterations).

usage: python -I scripts/gen_peak_kern.py     (from the repository root)
"""
OUT = "bench/peak_kern.c"
# name: (weight loads: 0 none, 1 LDP, 2 LDR pairs; A row loads: 0 / 1)
VARIANTS = {"noload": (0, 0), "w_ldp": (1, 0), "a_ldr": (0, 1),
            "kernel": (1, 1), "kernel_ldr": (2, 1)}
NOW_S = ("static double now_s(void) { struct timespec t; "
         "clock_gettime(CLOCK_MONOTONIC, &t); "
         "return t.tv_sec + t.tv_nsec * 1e-9; }")
POINTERS = ("    const float *w = buf, *p0 = buf + 8192, *p1 = p0 + 64, "
            "*p2 = p1 + 64, *p3 = p2 + 64, *p4 = p3 + 64, *p5 = p4 + 64, "
            "*p6 = p5 + 64, *p7 = p6 + 64;")
OPERANDS = ('      : [p0] "+r"(p0), [p1] "+r"(p1), [p2] "+r"(p2), '
            '[p3] "+r"(p3), [p4] "+r"(p4), [p5] "+r"(p5), [p6] "+r"(p6),',
            '        [p7] "+r"(p7), [w] "+r"(w), [n] "+r"(k)',
            "      :")
PRINTF = ('printf("%-12s %.3f G FMLA/s  (%.1f%% of 1/cycle at 1.5 GHz)\\n", '
          '"{nm}", 64.0 * n / t * 1e-9, 64.0 * n / t / 1.5e9 * 100);')


def k_loop(a, wl, al):
    """The 4-k iteration with the variant's loads."""
    for k in range(4):
        cur = 8 if k % 2 == 0 else 10
        nxt = 10 if k % 2 == 0 else 8
        if wl == 1:
            a(f'      "ldp q{nxt}, q{nxt+1}, [%[w]], #32\\n"')
        elif wl == 2:
            a(f'      "ldr q{nxt}, [%[w]], #16\\n"')
            a(f'      "ldr q{nxt+1}, [%[w]], #16\\n"')
        for r in range(8):
            a(f'      "fmla v{16+2*r}.4s, v{cur}.4s, v{r}.s[{k}]\\n"')
            a(f'      "fmla v{17+2*r}.4s, v{cur+1}.4s, v{r}.s[{k}]\\n"')
            if k == 3 and al:
                a(f'      "ldr q{r}, [%[p{r}]], #16\\n"')
    if not wl:
        a('      "add %[w], %[w], #128\\n"')
    a('      "subs %[n], %[n], #1\\n"')
    a('      "b.ne 1b\\n"')


def run_function(a, nm, wl, al):
    """run_<nm>(n, buf): the timed loop of one variant."""
    a(f"static double run_{nm}(long n, const float *buf) {{")
    a("  double t = now_s();")
    a("  for (long i = 0; i < n; i += 256) {")
    a(POINTERS)
    a("    long k = 256;")
    a("    __asm__ volatile(")
    for r in range(8):
        a(f'      "ldr q{r}, [%[p{r}]], #16\\n"')
    a('      "ldp q8, q9, [%[w]], #32\\n"')
    a('      "1:\\n"')
    k_loop(a, wl, al)
    for line in OPERANDS:
        a(line)
    clob = ", ".join(f'"v{i}"' for i in list(range(12)) + list(range(16, 32)))
    a(f'      : {clob}, "cc", "memory");')
    a("  }")
    a("  return now_s() - t;")
    a("}")


def main():
    lines = ["// generated by scripts/gen_peak_kern.py - do not edit",
             "#include <stdio.h>\n#include <stdlib.h>\n#include <string.h>\n"
             "#include <time.h>", NOW_S]
    a = lines.append
    for nm, (wl, al) in VARIANTS.items():
        run_function(a, nm, wl, al)
    a("int main(void) {")
    a("  float *buf = aligned_alloc(64, 1 << 18); memset(buf, 0, 1 << 18);")
    a("  long n = 4000000;")
    for nm in VARIANTS:
        a(f"  {{ double t = run_{nm}(n, buf); " + PRINTF.format(nm=nm) + " }")
    a("  free(buf); return 0;\n}")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
